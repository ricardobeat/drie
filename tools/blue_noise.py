#!/usr/bin/env python3
# Generates src/postprocessing/blue_noise.c3: a 64x64 tileable blue-noise threshold map (each of
# 0..4095 once, as the rank scaled to 0..255) by void-and-cluster (Ulichney 1993), for the dither
# in OutputPass. Pure Python, about half a minute:
#
#   python3 tools/blue_noise.py
import math, random, sys

N = 64
SIGMA = 1.9
CELLS = N * N
OUT = "src/postprocessing/blue_noise.c3"

# Toroidal Gaussian, its weights by offset (only offsets within 3 sigma matter).
R = int(math.ceil(SIGMA * 3))
KERNEL = [(dx, dy, math.exp(-(dx * dx + dy * dy) / (2 * SIGMA * SIGMA)))
          for dy in range(-R, R + 1) for dx in range(-R, R + 1)]


def splat(energy, i, sign):
    x, y = i % N, i // N
    for dx, dy, w in KERNEL:
        energy[(y + dy) % N * N + (x + dx) % N] += sign * w


def tightest(energy, on):
    return max((i for i in range(CELLS) if on[i]), key=lambda i: energy[i])


def largest_void(energy, on):
    return min((i for i in range(CELLS) if not on[i]), key=lambda i: energy[i])


def main():
    rng = random.Random(1)
    on = [False] * CELLS
    energy = [0.0] * CELLS
    # Initial pattern: a tenth of the cells, then relaxed until the tightest cluster is the
    # largest void.
    for i in rng.sample(range(CELLS), CELLS // 10):
        on[i] = True
        splat(energy, i, 1)
    while True:
        c = tightest(energy, on)
        on[c] = False
        splat(energy, c, -1)
        v = largest_void(energy, on)
        if v == c:
            on[c] = True
            splat(energy, c, 1)
            break
        on[v] = True
        splat(energy, v, 1)
    proto, proto_energy = on[:], energy[:]
    ones = sum(on)
    rank = [0] * CELLS
    # Phase 1: take out the tightest clusters, ranks ones-1 down to 0.
    for r in range(ones - 1, -1, -1):
        c = tightest(energy, on)
        on[c] = False
        splat(energy, c, -1)
        rank[c] = r
    # Phases 2 and 3: fill the largest voids, ranks ones up to CELLS-1.
    on, energy = proto, proto_energy
    for r in range(ones, CELLS):
        v = largest_void(energy, on)
        on[v] = True
        splat(energy, v, 1)
        rank[v] = r
    values = [r * 256 // CELLS for r in rank]

    lines = []
    for row in range(N):
        lines.append("    " + ", ".join(str(v) for v in values[row * N:(row + 1) * N]) + ",")
    with open(OUT, "w") as f:
        f.write("// Generated by tools/blue_noise.py: a 64x64 tileable blue-noise threshold map (void and\n")
        f.write("// cluster), each value 0..255 the same number of times. OutputPass's dither.\n")
        f.write("module drie::postprocessing;\n\n")
        f.write("const int BLUE_NOISE_SIZE = %d;\n" % N)
        f.write("char[*] blue_noise_data @private = {\n" + "\n".join(lines) + "\n};\n")
    print("wrote", OUT, file=sys.stderr)


main()
